export class AudioSystem {
  constructor({ catalog = AUDIO_CATALOG, audioFactory = (src) => new Audio(src), contextFactory = () => new (globalThis.AudioContext ?? globalThis.webkitAudioContext)() } = {}) {
    this.catalog = catalog;
    this.audioFactory = audioFactory;
    this.contextFactory = contextFactory;
    this.context = null;
    this.enabled = true;
    this.masterVolume = 0.7;
    this.activeLoop = null;
    this.loopHandle = null;
  }

  configure(settings = {}) {
    this.enabled = settings.enabled !== false;
    this.masterVolume = Math.max(0, Math.min(1, settings.masterVolume ?? 0.7));
  }

  async unlock() {
    if (!this.enabled) return;
    this.context = this.context ?? this.contextFactory();
    if (this.context.state === "suspended") await this.context.resume();
  }

  play(key, options = {}) {
    if (!this.enabled) return;
    const entry = this.catalog[key];
    if (!entry) return;
    const file = this.pickFile(entry);
    if (file) {
      return this.playFile(file, { loop: options.loop ?? entry.loop, volume: options.volume, fallback: entry.fallback });
    }
    this.playFallback(entry.fallback, options.volume);
    return null;
  }

  playForMission(mission = null) {
    if (!mission) return this.play("mission_scene", { volume: 0.45 });
    if (mission.id === "forest_signs" || mission.id === "old_road") return this.play("forest_ambience", { volume: 0.4 });
    if (mission.id === "transformation" || mission.id === "real_battle" || mission.type?.includes("Chefe")) return this.play("fear", { volume: 0.55 });
    if (mission.type?.includes("Defesa") || mission.type?.includes("batalha") || mission.type?.includes("Assalto")) return this.play("combat_start", { volume: 0.55 });
    return this.play("mission_scene", { volume: 0.45 });
  }

  playAttack(unit = null, result = null) {
    if (unit?.weapon === "bow" || unit?.weapon === "fire_bow") {
      this.play("bow_attack", { volume: 0.75 });
      if (unit.weapon === "fire_bow") this.play("fire", { volume: 0.48 });
      return;
    }
    this.play("sword_attack", { volume: result?.hit === false ? 0.45 : 0.72 });
    if (result?.hit !== false) this.play("armor_hit", { volume: 0.55 });
  }

  startLoop(key) {
    if (this.activeLoop === key) return;
    this.stopLoop();
    this.activeLoop = key;
    this.loopHandle = this.play(key, { loop: true, volume: 0.32 });
  }

  stopLoop() {
    if (this.loopHandle?.pause) {
      this.loopHandle.pause();
      this.loopHandle.currentTime = 0;
    }
    this.activeLoop = null;
    this.loopHandle = null;
  }

  pickFile(entry) {
    if (!entry.files?.length) return null;
    const index = Math.floor(Math.random() * entry.files.length);
    return entry.files[index];
  }

  playFile(src, { loop = false, volume = 1, fallback = "click" } = {}) {
    try {
      const audio = this.audioFactory(src);
      audio.volume = this.masterVolume * volume;
      audio.loop = loop;
      audio.play().catch(() => this.playFallback(fallback, volume));
      return audio;
    } catch {
      this.playFallback(fallback, volume);
      return null;
    }
  }

  playFallback(type = "click", volume = 1) {
    try {
      this.context = this.context ?? this.contextFactory();
      const now = this.context.currentTime;
      const gain = this.context.createGain();
      gain.gain.setValueAtTime(0.0001, now);
      gain.gain.exponentialRampToValueAtTime(Math.max(0.01, this.masterVolume * volume * 0.22), now + 0.015);
      gain.gain.exponentialRampToValueAtTime(0.0001, now + fallbackDuration(type));
      gain.connect(this.context.destination);

      for (const tone of fallbackTones(type)) {
        const osc = this.context.createOscillator();
        osc.type = tone.wave;
        osc.frequency.setValueAtTime(tone.start, now + tone.delay);
        osc.frequency.exponentialRampToValueAtTime(tone.end, now + tone.delay + tone.length);
        osc.connect(gain);
        osc.start(now + tone.delay);
        osc.stop(now + tone.delay + tone.length);
      }
    } catch {
      // Browsers can block audio before user interaction; silence is acceptable here.
    }
  }
}

function fallbackDuration(type) {
  return {
    click: 0.08,
    chime: 0.34,
    drone: 1.2,
    lowPulse: 0.7,
    wind: 1.0,
    hit: 0.18,
    slash: 0.16,
    metal: 0.22,
    whoosh: 0.2,
    fire: 0.55,
    fear: 0.9,
    victory: 0.9,
    defeat: 0.8
  }[type] ?? 0.12;
}

